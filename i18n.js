function detectSystemLanguage() {
    let rawLang = 'en';
    try {
        if (typeof chrome !== 'undefined' && chrome.i18n && typeof chrome.i18n.getUILanguage === 'function') {
            rawLang = chrome.i18n.getUILanguage();
        } else if (navigator.language) {
            rawLang = navigator.language;
        }
    } catch (e) {
        rawLang = navigator.language || 'en';
    }

    if (!rawLang) return 'en';
    const code = rawLang.toLowerCase().split('-')[0].split('_')[0];
    return translations[code] ? code : 'en';
}

let currentLang = detectSystemLanguage();

function getTranslation(key) {
    if (translations[currentLang] && translations[currentLang][key]) {
        return translations[currentLang][key];
    }
    if (translations.en && translations.en[key]) {
        return translations.en[key];
    }
    return key;
}

function setLanguage(lang) {
    if (translations[lang]) {
        currentLang = lang;
    } else {
        currentLang = 'en';
    }
    applyTranslations();
}

function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (key) {
            el.textContent = getTranslation(key);
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (key) {
            el.placeholder = getTranslation(key);
        }
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (key) {
            el.title = getTranslation(key);
        }
    });
}

if (typeof document !== 'undefined') {
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', applyTranslations);
    } else {
        applyTranslations();
    }
}
